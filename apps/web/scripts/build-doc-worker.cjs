/* eslint-disable @typescript-eslint/no-require-imports -- Browserify uses CommonJS entry points. */
const browserify = require('browserify');
const fs = require('node:fs');
const path = require('node:path');
const directory = path.join(__dirname, '../public/workers');
fs.mkdirSync(directory, { recursive: true });
const packages = new Map();
const bundle = browserify(path.join(__dirname, 'doc-worker.cjs'));
bundle.on('package', (pkg) => {
  if (!pkg.name || pkg.private || packages.has(pkg.name)) return;
  const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'COPYING'].map((name) => path.join(pkg.__dirname, name)).find((file) => fs.existsSync(file));
  packages.set(pkg.name, `${pkg.name} ${pkg.version}\nLicense: ${typeof pkg.license === 'string' ? pkg.license : JSON.stringify(pkg.license)}\n${license ? fs.readFileSync(license, 'utf8') : 'See the package repository for license text.'}\n`);
});
bundle.bundle((error, buffer) => {
  if (error) { console.error(error); process.exitCode = 1; return; }
  fs.writeFileSync(path.join(directory, 'doc-parser.js'), '/* Generated by npm run build:doc-worker. Licenses: doc-parser-LICENSES.txt. */\n' + buffer);
  fs.writeFileSync(path.join(directory, 'doc-parser-LICENSES.txt'), [...packages.values()].join('\n--------------------\n\n'));
  console.log('DOC worker built.');
});
